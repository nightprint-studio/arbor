/// Test if a (possibly out-of-range / END) phoneme has the given flag.
/// `None` (END) → false, matching JS's `phonemeFlags[null] → undefined`.
#[inline]
pub fn phoneme_has_flag(phoneme: Option<i32>, flag: u16) -> bool {
    match phoneme {
        Some(p) if (0..PHONEME_FLAGS.len() as i32).contains(&p) => {
            (PHONEME_FLAGS[p as usize] & flag) != 0
        }
        _ => false,
    }
}
