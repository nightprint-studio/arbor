//! The `CATALINA_BASE` a run configuration gets.
//!
//! Tomcat separates the *installation* (`CATALINA_HOME`: binaries, shared by everyone) from the
//! *instance* (`CATALINA_BASE`: configuration, logs, work files, applications). Giving each
//! configuration its own base is what lets several run side by side on one installation, lets the
//! installation stay untouched, and makes "what is this server running?" a folder one can open.
//!
//! The base is **regenerated at every launch**: `conf/server.xml`, the context, and `lib/` are
//! rebuilt from the configuration, so the files are an output and nobody has to wonder whether they
//! drifted. `logs/`, `temp/` and `work/` are kept — compiled JSPs are what makes the second start
//! quick.

use std::path::{Path, PathBuf};

/// What a base is made from.
#[derive(Debug, Clone)]
pub struct BaseSetup {
    pub http_port: u16,
    pub shutdown_port: u16,
    /// The file name inside `conf/Catalina/localhost/` (see [`crate::context::context_file_name`]).
    pub context_file: String,
    /// The rendered `context.xml`.
    pub context_xml: String,
    /// Jars copied into the base's `lib/` — the JDBC drivers, which must be visible to Tomcat's own
    /// class loader for a `<Resource>` to be created.
    pub lib_jars: Vec<PathBuf>,
}

/// The `conf/server.xml` of a base: one HTTP connector, one host, nothing else. A *generated* file
/// can afford to be minimal — the stock one is mostly commented-out examples.
pub fn render_server_xml(http_port: u16, shutdown_port: u16) -> String {
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Bennu. Ports come from the run configuration; do not edit — it is rewritten at every launch. -->
<Server port="{shutdown_port}" shutdown="SHUTDOWN">
  <Listener className="org.apache.catalina.startup.VersionLoggerListener" />
  <Service name="Catalina">
    <Connector port="{http_port}" protocol="HTTP/1.1" connectionTimeout="20000" URIEncoding="UTF-8" />
    <Engine name="Catalina" defaultHost="localhost">
      <Host name="localhost" appBase="webapps" unpackWARs="true" autoDeploy="false" />
    </Engine>
  </Service>
</Server>
"#
    )
}

fn io(what: &str, path: &Path, e: std::io::Error) -> String {
    format!("{what} {}: {e}", path.display())
}

fn recreate_dir(dir: &Path) -> Result<(), String> {
    if dir.exists() {
        std::fs::remove_dir_all(dir).map_err(|e| io("Could not clear", dir, e))?;
    }
    std::fs::create_dir_all(dir).map_err(|e| io("Could not create", dir, e))
}

/// Build (or rebuild) the base at `base` from the installation at `home`.
pub fn prepare_base(home: &Path, base: &Path, setup: &BaseSetup) -> Result<(), String> {
    for kept in ["logs", "temp", "work", "webapps", "conf"] {
        std::fs::create_dir_all(base.join(kept)).map_err(|e| io("Could not create", &base.join(kept), e))?;
    }
    // Files Tomcat reads from `conf/` and that a base has to carry itself: without `web.xml` no
    // servlet, no JSP; without `logging.properties` the console stays silent.
    for name in ["web.xml", "logging.properties", "catalina.properties", "catalina.policy", "context.xml"] {
        let from = home.join("conf").join(name);
        if from.is_file() {
            std::fs::copy(&from, base.join("conf").join(name)).map_err(|e| io("Could not copy", &from, e))?;
        }
    }
    std::fs::write(base.join("conf/server.xml"), render_server_xml(setup.http_port, setup.shutdown_port))
        .map_err(|e| io("Could not write", &base.join("conf/server.xml"), e))?;

    let localhost = base.join("conf/Catalina/localhost");
    recreate_dir(&localhost)?;
    std::fs::write(localhost.join(&setup.context_file), &setup.context_xml)
        .map_err(|e| io("Could not write", &localhost.join(&setup.context_file), e))?;

    let lib = base.join("lib");
    recreate_dir(&lib)?;
    for jar in &setup.lib_jars {
        let Some(name) = jar.file_name() else { continue };
        std::fs::copy(jar, lib.join(name)).map_err(|e| io("Could not copy driver", jar, e))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("bennu-tomcat-base-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn server_xml_carries_both_ports() {
        let xml = render_server_xml(8081, 8006);
        assert!(xml.contains("<Server port=\"8006\" shutdown=\"SHUTDOWN\">"), "{xml}");
        assert!(xml.contains("<Connector port=\"8081\""), "{xml}");
        assert!(xml.contains("autoDeploy=\"false\""), "an explicit context is the only thing deployed: {xml}");
    }

    #[test]
    fn a_base_is_rebuilt_but_its_logs_survive() {
        let d = temp("rebuild");
        let (home, base) = (d.join("home"), d.join("base"));
        std::fs::create_dir_all(home.join("conf")).unwrap();
        std::fs::write(home.join("conf/web.xml"), "<web-app/>").unwrap();
        let jar = d.join("pg.jar");
        std::fs::write(&jar, b"jar").unwrap();

        let mut setup = BaseSetup {
            http_port: 8080,
            shutdown_port: 8005,
            context_file: "app.xml".into(),
            context_xml: "<Context/>".into(),
            lib_jars: vec![jar],
        };
        prepare_base(&home, &base, &setup).unwrap();
        assert!(base.join("conf/web.xml").is_file() && base.join("conf/Catalina/localhost/app.xml").is_file());
        assert!(base.join("lib/pg.jar").is_file());
        std::fs::write(base.join("logs/catalina.out"), "history").unwrap();
        std::fs::write(base.join("conf/Catalina/localhost/stale.xml"), "x").unwrap();

        setup.lib_jars.clear();
        setup.context_file = "other.xml".into();
        prepare_base(&home, &base, &setup).unwrap();
        assert!(!base.join("conf/Catalina/localhost/stale.xml").exists(), "generated files are an output");
        assert!(!base.join("conf/Catalina/localhost/app.xml").exists());
        assert!(base.join("conf/Catalina/localhost/other.xml").is_file());
        assert!(!base.join("lib/pg.jar").exists());
        assert_eq!(std::fs::read_to_string(base.join("logs/catalina.out")).unwrap(), "history");
        let _ = std::fs::remove_dir_all(&d);
    }
}
