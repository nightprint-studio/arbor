//! The application's `context.xml`, generated from the run configuration.
//!
//! It is written to `conf/Catalina/localhost/<name>.xml` of the generated base — **not** into the
//! project's `META-INF/` — so development credentials never end up in a WAR or in the repository.
//!
//! Two things shape it:
//!
//! * **A data source's password is never typed here in secret mode.** The attribute holds
//!   `${jdbc.Gestionale.password}`, which Tomcat resolves from a system property at start-up; the
//!   backend supplies the property on the command line. The file on disk carries no secret, and
//!   neither does the repository.
//! * **A live deployment is described as resources.** Tomcat serves `src/main/webapp`, with the
//!   module's compiled classes mounted at `/WEB-INF/classes` and each runtime dependency at
//!   `/WEB-INF/lib` — the way an IDE deploys, with nothing packaged.

use bennu_proto::prelude::{TomcatResource, TomcatRunConfig};

/// How a mount is backed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MountKind {
    /// A directory (`DirResourceSet`) — compiled classes.
    Dir,
    /// A single file (`FileResourceSet`) — one dependency jar.
    File,
}

/// One extra resource set mounted into the web application.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mount {
    pub kind: MountKind,
    /// The directory or file on disk.
    pub base: String,
    /// Where it appears inside the application (`/WEB-INF/classes`).
    pub web_app_mount: String,
}

/// What [`render_context`] needs besides the configuration.
#[derive(Debug, Clone, Default)]
pub struct ContextInput {
    /// What `docBase` is: the webapp directory (live) or the exploded directory / `.war` (external).
    pub doc_base: String,
    pub mounts: Vec<Mount>,
}

/// The file a context path is stored under: `/` → `ROOT.xml`, `/a/b` → `a#b.xml` — Tomcat's own
/// naming, which is also what decides the path the application is served under.
pub fn context_file_name(context_path: &str) -> String {
    let trimmed = context_path.trim().trim_matches('/');
    if trimmed.is_empty() {
        "ROOT.xml".to_string()
    } else {
        format!("{}.xml", trimmed.replace('/', "#"))
    }
}

/// The system property a secret password is handed over as: `jdbc/Gestionale` →
/// `jdbc.Gestionale.password`.
pub fn secret_property(resource_name: &str) -> String {
    let mut out = String::new();
    let mut last_dot = true;
    for c in resource_name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
            last_dot = false;
        } else if !last_dot {
            out.push('.');
            last_dot = true;
        }
    }
    let out = out.trim_end_matches('.');
    if out.is_empty() { "resource.password".to_string() } else { format!("{out}.password") }
}

fn attr(value: &str) -> String {
    value.replace('&', "&amp;").replace('"', "&quot;").replace('<', "&lt;").replace('\n', "&#10;")
}

fn datasource(r: &TomcatResource, out: &mut Vec<String>) {
    let password = if r.password_mode == "clear" {
        attr(&r.password)
    } else {
        // `${…}` is Tomcat's own substitution, resolved from a system property.
        format!("${{{}}}", secret_property(&r.name))
    };
    out.push(format!(
        "  <Resource name=\"{}\" auth=\"Container\" type=\"javax.sql.DataSource\"",
        attr(&r.name)
    ));
    out.push(format!("            driverClassName=\"{}\"", attr(&r.driver)));
    out.push(format!("            url=\"{}\"", attr(&r.url)));
    out.push(format!("            username=\"{}\" password=\"{password}\"", attr(&r.user)));
    out.push(format!(
        "            maxTotal=\"{}\" maxIdle=\"{}\" maxWaitMillis=\"{}\"",
        r.max_total, r.max_idle, r.max_wait_ms
    ));
    let mut tail = String::from("            ");
    if !r.validation_query.trim().is_empty() {
        tail.push_str(&format!("validationQuery=\"{}\" ", attr(&r.validation_query)));
    }
    tail.push_str(&format!("testOnBorrow=\"{}\"/>", r.test_on_borrow));
    out.push(tail);
}

/// The generated `context.xml` for `cfg`. In `raw` mode that is the configuration's own text.
pub fn render_context(cfg: &TomcatRunConfig, input: &ContextInput) -> String {
    if cfg.context_mode == "raw" && !cfg.context_raw.trim().is_empty() {
        return cfg.context_raw.clone();
    }
    let mut out = vec![
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>".to_string(),
        format!(
            "<!-- Generated by Bennu for {} — edit it from the run configuration. -->",
            context_file_name(&cfg.context_path)
        ),
        format!(
            "<Context docBase=\"{}\"{}>",
            attr(&input.doc_base),
            if cfg.reloadable { " reloadable=\"true\"" } else { "" }
        ),
    ];
    if !input.mounts.is_empty() {
        out.push("  <Resources>".to_string());
        for m in &input.mounts {
            let class = match m.kind {
                MountKind::Dir => "org.apache.catalina.webresources.DirResourceSet",
                MountKind::File => "org.apache.catalina.webresources.FileResourceSet",
            };
            out.push(format!(
                "    <PostResources className=\"{class}\" base=\"{}\" webAppMount=\"{}\"/>",
                attr(&m.base),
                attr(&m.web_app_mount)
            ));
        }
        out.push("  </Resources>".to_string());
    }
    for r in &cfg.resources {
        if r.name.trim().is_empty() {
            continue;
        }
        match r.kind.as_str() {
            "datasource" => datasource(r, &mut out),
            "env" => out.push(format!(
                "  <Environment name=\"{}\" value=\"{}\" type=\"{}\" override=\"{}\"/>",
                attr(&r.name),
                attr(&r.value),
                attr(&r.value_type),
                r.allow_override
            )),
            _ => out.push(format!(
                "  <Parameter name=\"{}\" value=\"{}\" override=\"false\"/>",
                attr(&r.name),
                attr(&r.value)
            )),
        }
    }
    out.push("</Context>".to_string());
    out.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ds(name: &str, mode: &str) -> TomcatResource {
        TomcatResource {
            kind: "datasource".into(),
            name: name.into(),
            driver: "org.postgresql.Driver".into(),
            url: "jdbc:postgresql://h/db?a=1&b=2".into(),
            user: "app".into(),
            password_mode: mode.into(),
            password: if mode == "clear" { "p\"w".into() } else { String::new() },
            ..TomcatResource::default()
        }
    }

    #[test]
    fn a_context_path_names_its_file_the_way_tomcat_reads_it() {
        assert_eq!(context_file_name("/"), "ROOT.xml");
        assert_eq!(context_file_name(""), "ROOT.xml");
        assert_eq!(context_file_name("/gestionale"), "gestionale.xml");
        assert_eq!(context_file_name("/a/b/"), "a#b.xml");
    }

    #[test]
    fn a_secret_property_is_a_dotted_name() {
        assert_eq!(secret_property("jdbc/Gestionale"), "jdbc.Gestionale.password");
        assert_eq!(secret_property("//x  y//"), "x.y.password");
        assert_eq!(secret_property("///"), "resource.password");
    }

    #[test]
    fn a_secret_password_is_a_reference_and_never_the_value() {
        let cfg = TomcatRunConfig { resources: vec![ds("jdbc/G", "secret")], ..TomcatRunConfig::default() };
        let xml = render_context(&cfg, &ContextInput { doc_base: "/w".into(), mounts: vec![] });
        assert!(xml.contains("password=\"${jdbc.G.password}\""), "{xml}");
        assert!(xml.contains("a=1&amp;b=2"), "attribute values are escaped: {xml}");
        assert!(xml.contains("docBase=\"/w\"") && !xml.contains("reloadable"), "{xml}");
    }

    #[test]
    fn a_clear_password_is_written_escaped() {
        let cfg = TomcatRunConfig { resources: vec![ds("jdbc/G", "clear")], ..TomcatRunConfig::default() };
        let xml = render_context(&cfg, &ContextInput::default());
        assert!(xml.contains("password=\"p&quot;w\""), "{xml}");
    }

    #[test]
    fn a_live_deployment_mounts_classes_and_jars() {
        let cfg = TomcatRunConfig { reloadable: true, ..TomcatRunConfig::default() };
        let xml = render_context(
            &cfg,
            &ContextInput {
                doc_base: "/w".into(),
                mounts: vec![
                    Mount { kind: MountKind::Dir, base: "/m/target/classes".into(), web_app_mount: "/WEB-INF/classes".into() },
                    Mount { kind: MountKind::File, base: "/r/x.jar".into(), web_app_mount: "/WEB-INF/lib/x.jar".into() },
                ],
            },
        );
        assert!(xml.contains("DirResourceSet") && xml.contains("FileResourceSet"), "{xml}");
        assert!(xml.contains("webAppMount=\"/WEB-INF/lib/x.jar\"") && xml.contains("reloadable=\"true\""), "{xml}");
    }

    #[test]
    fn environment_and_parameter_entries_render_and_blank_names_are_skipped() {
        let cfg = TomcatRunConfig {
            resources: vec![
                TomcatResource { kind: "env".into(), name: "app/modalita".into(), value: "dev".into(), ..TomcatResource::default() },
                TomcatResource { kind: "param".into(), name: "p".into(), value: "v".into(), ..TomcatResource::default() },
                TomcatResource { kind: "env".into(), name: "  ".into(), ..TomcatResource::default() },
            ],
            ..TomcatRunConfig::default()
        };
        let xml = render_context(&cfg, &ContextInput::default());
        assert!(xml.contains("<Environment name=\"app/modalita\" value=\"dev\" type=\"java.lang.String\" override=\"false\"/>"), "{xml}");
        assert!(xml.contains("<Parameter name=\"p\" value=\"v\" override=\"false\"/>"), "{xml}");
        assert_eq!(xml.matches("<Environment").count(), 1);
    }

    #[test]
    fn raw_mode_is_written_as_typed() {
        let cfg = TomcatRunConfig { context_mode: "raw".into(), context_raw: "<Context/>".into(), ..TomcatRunConfig::default() };
        assert_eq!(render_context(&cfg, &ContextInput::default()), "<Context/>");
    }
}
