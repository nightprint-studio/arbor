<h1>Sources</h1>
<p class="doc-lead">
  The source is <b>what</b> gets captured. Switch it from the segmented control
  next to the “Source” heading, or cycle it with
  <kbd>Ctrl</kbd>+<kbd>Shift</kbd>+<kbd>S</kbd>.
</p>

<h2>Monitor</h2>
<p>
  Capture a whole display. Each connected monitor is shown as a tile with its
  resolution and scale factor; the primary display is marked. Pick one to make it
  the target.
</p>

<h2>Window</h2>
<p>
  Capture a single application window. Open windows are shown as a clean grid of
  tiles (app badge + title), sorted by name; with many open, filter them by title
  or process name with the search box. A <b>live preview</b> of the selected window
  sits above the grid, so you can confirm the right one before capturing.
</p>

<h2>Region</h2>
<p>
  Capture a freely-drawn rectangle. See
  <a href="#region">Region selection</a> for how the selection overlay works.
</p>
