<h1>Getting Started</h1>
<p class="doc-lead">
  Tyto records your screen and takes screenshots. Pick <b>what</b> to capture,
  tune the <b>options</b>, then fire the action from the titlebar — everything is
  reachable from the keyboard.
</p>

<div class="callout accent">
  Recordings and screenshots are real — they need the Tyto backend and a bundled
  ffmpeg (provisioned on first run). Audio can capture your <b>microphone</b>, the
  <b>system output</b>, or both mixed together. Region selection opens an opaque
  full-screen overlay over a frozen snapshot of the desktop.
</div>

<h2>The window at a glance</h2>
<ul>
  <li><b>Titlebar</b> — the mode switch (Recording / Screenshot), the primary
    capture action, the documentation button and the settings gear.</li>
  <li><b>Capture panel</b> — a live preview of the current target, the source
    picker and the mode-specific options.</li>
  <li><b>Library</b> — the dock on the right listing everything you've captured.
    Toggle it with <kbd>Ctrl</kbd>+<kbd>Shift</kbd>+<kbd>B</kbd>.</li>
</ul>

<h2>Your first capture</h2>
<ol class="step-list">
  <li>Choose a source — a whole <b>Monitor</b>, a single <b>Window</b>, or a
    dragged <b>Region</b>.</li>
  <li>Set your options (frame rate, quality and audio for recordings; format for
    screenshots).</li>
  <li>Press the capture action in the titlebar, or <kbd>Ctrl</kbd>+<kbd>Enter</kbd>.</li>
  <li>Find the result in the library, where you can rename, preview, reveal or
    delete it.</li>
</ol>

<h2>Opening Tyto from anywhere</h2>
<p>
  In <b>Settings</b> you can enable an OS-global shortcut that opens Tyto even
  when Arbor isn't focused. It's off by default and fully rebindable.
</p>
